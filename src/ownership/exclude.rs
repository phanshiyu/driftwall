//! Which source files are not the project's own: vendored, minified and generated code.

use std::ffi::OsStr;
use std::path::{Component, Path};

use crate::code::Exclusion;

/// Directory names whose whole subtree is vendored code.
const VENDOR_DIRECTORIES: [&str; 2] = ["vendor", "third_party"];
/// Directory names whose whole subtree is build output.
const GENERATED_DIRECTORIES: [&str; 1] = ["dist"];
/// The dot-separated name part that marks a minified file (`app.min.js`).
const MINIFIED_PART: &str = "min";
/// Lower-case phrases that mark a file as generated when one of its first lines holds one.
const GENERATED_MARKERS: [&str; 4] = [
    "@generated",
    "do not edit",
    "auto-generated",
    "autogenerated",
];
/// How many lines at the top of a file may announce that it is generated.
pub const HEADER_LINES: usize = 5;

/// The reason `file` is excluded from the scan by its path, or `None` when only its contents could
/// tell (see [`announces_generated`]).
///
/// A file below a directory named `vendor` or `third_party` is [`Exclusion::Vendored`]. A file
/// whose second to last dot-separated name part is exactly `min` (`htmx.min.js`, `site.min.css`)
/// is [`Exclusion::Minified`]. A file below a directory named `dist` is [`Exclusion::Generated`].
/// The first of these that applies wins. The path is repository-relative.
#[must_use]
pub fn exclusion_of(file: &Path) -> Option<Exclusion> {
    if in_directory_named(file, &VENDOR_DIRECTORIES) {
        return Some(Exclusion::Vendored);
    }
    if is_minified_name(file) {
        return Some(Exclusion::Minified);
    }
    in_directory_named(file, &GENERATED_DIRECTORIES).then_some(Exclusion::Generated)
}

/// Whether one of the first [`HEADER_LINES`] lines of `contents` holds, ignoring case,
/// `@generated`, `do not edit`, `auto-generated` or `autogenerated`.
#[must_use]
pub fn announces_generated(contents: &str) -> bool {
    contents.lines().take(HEADER_LINES).any(|line| {
        let line = line.to_lowercase();
        GENERATED_MARKERS.iter().any(|marker| line.contains(marker))
    })
}

fn in_directory_named(file: &Path, names: &[&str]) -> bool {
    file.parent()
        .into_iter()
        .flat_map(Path::components)
        .any(|part| match part {
            Component::Normal(name) => names.iter().any(|wanted| name == *wanted),
            Component::Prefix(_)
            | Component::RootDir
            | Component::CurDir
            | Component::ParentDir => false,
        })
}

fn is_minified_name(file: &Path) -> bool {
    let Some(name) = file.file_name().and_then(OsStr::to_str) else {
        return false;
    };
    let mut parts = name.rsplit('.');
    let _extension = parts.next();
    let marker = parts.next();
    // why: `.min.js` alone is a hidden file called `.min`, not a minified `<name>.min.js`.
    marker == Some(MINIFIED_PART) && parts.next().is_some_and(|stem| !stem.is_empty())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn reason(path: &str) -> Option<Exclusion> {
        exclusion_of(Path::new(path))
    }

    #[test]
    fn minified_names_have_min_as_the_part_before_the_extension() {
        for name in [
            "htmx.min.js",
            "static/htmx.min.js",
            "a.min.mjs",
            "a.b.min.js",
            "site.min.css",
        ] {
            assert_eq!(reason(name), Some(Exclusion::Minified), "{name}");
        }
    }

    #[test]
    fn near_misses_are_source() {
        for name in [
            "min.js",
            "admin.js",
            "a.minx.js",
            "a.mini.js",
            "a.min",
            ".min.js",
            "minimal/a.js",
            "a.js",
        ] {
            assert_eq!(reason(name), None, "{name}");
        }
    }

    #[test]
    fn anything_below_a_vendor_directory_is_vendored() {
        for path in [
            "vendor/a.js",
            "ui/vendor/basecoat/basecoat.min.js",
            "a/third_party/b/c/d.rs",
            "vendor/x/y.py",
        ] {
            assert_eq!(reason(path), Some(Exclusion::Vendored), "{path}");
        }
    }

    #[test]
    fn only_whole_directory_names_count() {
        for path in [
            "vendors/a.js",
            "my_vendor/a.js",
            "third-party/a.js",
            "vendor.js",
        ] {
            assert_eq!(reason(path), None, "{path}");
        }
    }

    #[test]
    fn anything_below_a_dist_directory_is_generated() {
        for path in [
            "dist/a.js",
            "ui/dist/assets/index-4f9a1c.js",
            "a/dist/b/c.py",
        ] {
            assert_eq!(reason(path), Some(Exclusion::Generated), "{path}");
        }
        for path in [
            "distro/a.js",
            "dist.js",
            "my-dist/a.js",
            "src/dist-utils.ts",
        ] {
            assert_eq!(reason(path), None, "{path}");
        }
    }

    #[test]
    fn the_first_reason_wins_vendored_then_minified_then_generated() {
        assert_eq!(reason("dist/vendor/a.js"), Some(Exclusion::Vendored));
        assert_eq!(reason("vendor/dist/a.js"), Some(Exclusion::Vendored));
        assert_eq!(reason("dist/app.min.js"), Some(Exclusion::Minified));
    }

    #[test]
    fn the_first_lines_decide_whether_a_file_announces_itself_as_generated() {
        for head in [
            "// @generated\nexport const a = 1;\n",
            "/* Generated by tool. DO NOT EDIT. */\n",
            "#!/usr/bin/env python\n# Auto-Generated file\n",
            "\n\n\n\n// AUTOGENERATED\n",
            "// This file is not to be edited.\n// please do not edit it\n",
        ] {
            assert!(announces_generated(head), "{head:?}");
        }
        for head in [
            "",
            "export const a = 1;\n",
            "\n\n\n\n\n// do not edit (line 6)\n",
            "// generated code lives elsewhere\n// do  not  edit\n",
            "// do-not-edit\n",
        ] {
            assert!(!announces_generated(head), "{head:?}");
        }
    }

    #[test]
    fn the_exclusion_reasons_have_stable_words() {
        assert_eq!(Exclusion::Vendored.as_str(), "vendored");
        assert_eq!(Exclusion::Minified.as_str(), "minified");
        assert_eq!(Exclusion::Generated.as_str(), "generated");
    }
}
