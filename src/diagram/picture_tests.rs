#[test]
fn the_order_of_declarations_does_not_change_the_picture() {
    let mut reversed: Vec<&str> = EDGES.to_vec();
    reversed.reverse();
    let (a, b) = (contract(&EDGES), contract(&reversed));
    for view in [
        PictureView::Full,
        PictureView::Depth(1),
        PictureView::Depth(2),
        PictureView::Focus("billing".to_owned()),
    ] {
        assert_eq!(
            picture(&a, &view, "a.mmd"),
            picture(&b, &view, "a.mmd"),
            "{view:?}"
        );
    }
    assert_eq!(drawn(&PictureView::Full), drawn(&PictureView::Full));
}

