const BLOCK: &str =
    "# Title\n\n<!-- driftwall render --depth 1 -->\nold\n<!-- driftwall render end -->\n\ntext\n";

fn synced(markdown: &str) -> Result<crate::model::MarkdownSync, PictureError> {
    sync(markdown, &contract(&EDGES), "architecture.mmd")
}

#[test]
fn sync_replaces_the_inside_of_a_block_and_leaves_the_rest_alone() {
    let result = synced(BLOCK).unwrap();
    assert_eq!(result.stale, [3]);
    let picture = drawn(&PictureView::Depth(1));
    assert_eq!(
        result.text,
        format!(
            "# Title\n\n<!-- driftwall render --depth 1 -->\n```mermaid\n{picture}```\n<!-- driftwall render end -->\n\ntext\n"
        )
    );
    let again = synced(&result.text).unwrap();
    assert_eq!(again.stale, Vec::<u32>::new());
    assert_eq!(again.text, result.text);
}

#[test]
fn sync_handles_several_blocks_with_their_own_arguments() {
    let md = "<!-- driftwall render -->\n<!-- driftwall render end -->\nmid\n<!-- driftwall render --focus billing -->\nx\n<!-- driftwall render end -->";
    let result = synced(md).unwrap();
    assert_eq!(result.stale, [1, 4]);
    assert!(
        result.text.contains("--focus billing from"),
        "{}",
        result.text
    );
    assert!(result.text.ends_with("<!-- driftwall render end -->"));
    assert_eq!(synced(&result.text).unwrap().stale, Vec::<u32>::new());
}

#[test]
fn sync_keeps_crlf_line_endings() {
    let md = BLOCK.replace('\n', "\r\n");
    let result = synced(&md).unwrap();
    assert!(
        !result.text.replace("\r\n", "").contains('\n'),
        "{:?}",
        result.text
    );
    assert_eq!(synced(&result.text).unwrap().stale, Vec::<u32>::new());
}

#[test]
fn a_malformed_file_is_an_error_naming_the_line() {
    let start = "<!-- driftwall render -->\n";
    let end = "<!-- driftwall render end -->\n";
    assert_eq!(
        synced(&format!("a\n{start}b\n")),
        Err(PictureError::Unclosed { line: 2 })
    );
    assert_eq!(
        synced(&format!("a\n{end}")),
        Err(PictureError::StrayEnd { line: 2 })
    );
    assert_eq!(
        synced(&format!("{start}{start}{end}")),
        Err(PictureError::Nested { line: 2, first: 1 })
    );
    assert_eq!(synced("nothing here\n"), Err(PictureError::NoBlock));
    for args in [
        "--depth",
        "--depth x",
        "--focus",
        "--bogus 1",
        "--depth 1 --focus a",
    ] {
        let md = format!("a\n<!-- driftwall render {args} -->\n{end}");
        assert!(
            matches!(synced(&md), Err(PictureError::BadMarker { line: 2, .. })),
            "{args}"
        );
    }
    assert_eq!(
        synced(&format!("<!-- driftwall render --depth 0 -->\n{end}")),
        Err(PictureError::ZeroDepth)
    );
    assert_eq!(
        synced(&format!("<!-- driftwall render --focus nope -->\n{end}")),
        Err(PictureError::UnknownBoundary("nope".to_owned()))
    );
}

const LAYERS: &str = "flowchart LR
  subgraph app
    app-main
  end
  subgraph features
    subgraph billing
      billing-view
      billing-service
    end
  end
  subgraph ui
    ui-kit
    ui-extra
  end
  subgraph core
    core-db
    core-cache
  end
  %% order open: app > features > ui > core
";

fn open_arrows_of(extra: &str, view: &PictureView) -> Vec<String> {
    let contract = parse(&format!("{LAYERS}{extra}")).unwrap();
    picture(&contract, view, "a.mmd")
        .unwrap()
        .lines()
        .filter(|line| line.contains("==>"))
        .map(|line| line.trim().to_owned())
        .collect()
}

#[test]
fn with_nothing_narrowed_the_open_arrows_are_the_consecutive_layers() {
    assert_eq!(
        open_arrows_of("", &PictureView::Full),
        [
            "app ==>|open| features",
            "features ==>|open| ui",
            "ui ==>|open| core"
        ]
    );
}

#[test]
fn narrowing_removes_an_arrow_and_the_reduction_adds_the_skip() {
    assert_eq!(
        open_arrows_of("  %% each features: view --> ui-kit\n", &PictureView::Full),
        [
            "app ==>|open| features",
            "app ==>|open| ui",
            "features ==>|open| core",
            "ui ==>|open| core"
        ]
    );
}

#[test]
fn a_whole_layer_denial_removes_an_arrow() {
    assert_eq!(
        open_arrows_of("  %% deny ui: core\n", &PictureView::Full),
        [
            "app ==>|open| features",
            "features ==>|open| core",
            "features ==>|open| ui"
        ]
    );
}

#[test]
fn a_node_denial_that_leaves_a_pair_open_keeps_the_arrow() {
    assert_eq!(
        open_arrows_of("  %% deny ui-kit: core-db\n", &PictureView::Full),
        open_arrows_of("", &PictureView::Full)
    );
}

#[test]
fn open_arrows_collapse_and_merge_with_depth() {
    let extra = "  %% each features: view --> ui\n  %% deny ui: core\n";
    assert_eq!(
        open_arrows_of(extra, &PictureView::Depth(1)),
        [
            "app ==>|open| features",
            "app ==>|open| ui",
            "features ==>|open| core"
        ]
    );
    // why: `features` is a depth 1 boundary, so depth 2 draws the same arrows.
    assert_eq!(
        open_arrows_of(extra, &PictureView::Depth(2)),
        open_arrows_of(extra, &PictureView::Depth(1))
    );
}

