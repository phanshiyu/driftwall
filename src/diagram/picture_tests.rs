//! The picture of `driftwall render`: collapse, merge, focus and the Markdown blocks, see "Contract
//! picture" in `docs/DESIGN.md`.

use super::*;
use crate::model::{Contract, PictureView};

const HEAD: &str = "flowchart LR
  subgraph app[\"App\"]
    app-main
  end
  subgraph features[\"Features\"]
    subgraph billing[\"Billing\"]
      billing-view[\"View\"]
      billing-service
    end
    subgraph search[\"Search\"]
      search-view
    end
    features-shell
  end
  subgraph core[\"Core\"]
    core-ui
    core-db
  end
";

const EDGES: [&str; 9] = [
    "  app-main --> features-shell",
    "  billing-view --> billing-service",
    "  billing-view -->|test| core-ui",
    "  billing-service -->|type| core-ui",
    "  billing-service -.-> core-db",
    "  search-view -->|type| core-ui",
    "  features-shell --> billing-view",
    "  features --> core",
    "  %% order open: app > features > core",
];

fn contract(edges: &[&str]) -> Contract {
    parse(&format!("{HEAD}{}\n", edges.join("\n"))).unwrap()
}

fn drawn(view: &PictureView) -> String {
    picture(&contract(&EDGES), view, "architecture.mmd").unwrap()
}

fn lines(text: &str) -> Vec<&str> {
    text.lines().collect()
}

#[test]
fn the_full_picture_has_every_boundary_node_edge_and_open_arrow() {
    let text = drawn(&PictureView::Full);
    assert_eq!(
        lines(&text),
        [
            "%% generated by driftwall render from architecture.mmd; do not edit",
            "flowchart LR",
            "  subgraph app[\"App\"]",
            "    app-main",
            "  end",
            "  subgraph core[\"Core\"]",
            "    core-db",
            "    core-ui",
            "  end",
            "  subgraph features[\"Features\"]",
            "    subgraph billing[\"Billing\"]",
            "      billing-service",
            "      billing-view[\"View\"]",
            "    end",
            "    subgraph search[\"Search\"]",
            "      search-view",
            "    end",
            "    features-shell",
            "  end",
            "  app-main --> features-shell",
            "  billing-service -.-> core-db",
            "  billing-service -->|type| core-ui",
            "  billing-view --> billing-service",
            "  billing-view -->|test| core-ui",
            "  features --> core",
            "  features-shell --> billing-view",
            "  search-view -->|type| core-ui",
            // why: edges narrow app to features and features to core, so only the skip is open.
            "  app ==>|open| core",
        ]
    );
}

#[test]
fn the_picture_has_no_directives_and_no_maps() {
    let text = drawn(&PictureView::Full);
    assert_eq!(text.matches("%%").count(), 1, "{text}");
    assert!(!text.contains("order"), "{text}");
}

#[test]
fn depth_one_draws_top_level_boundaries_as_boxes_and_merges_their_edges() {
    let text = drawn(&PictureView::Depth(1));
    assert_eq!(
        lines(&text),
        [
            "%% generated by driftwall render --depth 1 from architecture.mmd; do not edit",
            "flowchart LR",
            "  app[\"App\"]",
            "  core[\"Core\"]",
            "  features[\"Features\"]",
            // why: app-main to features-shell is the only edge between the two.
            "  app --> features",
            // why: solid beats dotted, and `test`, `type` and none differ, so no label.
            "  features --> core",
            // why: edges narrow app to features and features to core, so only the skip is open.
            "  app ==>|open| core",
        ]
    );
}

#[test]
fn depth_two_draws_inner_boundaries_as_boxes_inside_their_parent() {
    let text = drawn(&PictureView::Depth(2));
    assert!(
        text.contains(
            "  subgraph features[\"Features\"]\n    billing[\"Billing\"]\n    search[\"Search\"]\n    features-shell\n  end\n"
        ),
        "{text}"
    );
    assert!(
        text.contains("  subgraph core[\"Core\"]\n    core-db\n"),
        "{text}"
    );
    // why: billing-view to billing-service has both ends in the box billing, so it is dropped.
    assert!(!text.contains("billing --> billing"), "{text}");
    assert!(text.contains("  billing --> core-ui\n"), "{text}");
    assert!(text.contains("  billing -.-> core-db\n"), "{text}");
    assert!(text.contains("  features-shell --> billing\n"), "{text}");
    assert!(text.contains("  search -->|type| core-ui\n"), "{text}");
    assert!(text.contains("  features --> core\n"), "{text}");
}

#[test]
fn a_depth_beyond_the_nesting_changes_nothing_but_the_header() {
    let full = drawn(&PictureView::Full);
    let deep = drawn(&PictureView::Depth(9));
    assert_eq!(
        full.lines().skip(1).collect::<Vec<_>>(),
        deep.lines().skip(1).collect::<Vec<_>>()
    );
}

#[test]
fn merged_edges_keep_a_label_only_when_every_edge_has_it() {
    let edges = [
        "  billing-service -->|type| core-ui",
        "  billing-view -->|type| core-db",
        "  search-view -.->|type| core-ui",
        "  search-view -.->|type| core-db",
    ];
    let text = picture(&contract(&edges), &PictureView::Depth(1), "a.mmd").unwrap();
    assert!(text.contains("  features -->|type| core\n"), "{text}");
    let edges = [
        "  billing-service -.->|test| core-ui",
        "  search-view -.->|test| core-db",
    ];
    let text = picture(&contract(&edges), &PictureView::Depth(1), "a.mmd").unwrap();
    assert!(text.contains("  features -.->|test| core\n"), "{text}");
    let edges = [
        "  billing-service -.->|type| core-ui",
        "  search-view -.->|type, test| core-db",
    ];
    let text = picture(&contract(&edges), &PictureView::Depth(1), "a.mmd").unwrap();
    assert!(text.contains("  features -.-> core\n"), "{text}");
}

#[test]
fn focus_draws_the_boundary_in_full_and_the_outside_as_its_outermost_boundary() {
    let text = drawn(&PictureView::Focus("billing".to_owned()));
    assert_eq!(
        lines(&text),
        [
            "%% generated by driftwall render --focus billing from architecture.mmd; do not edit",
            "flowchart LR",
            "  subgraph billing[\"Billing\"]",
            "    billing-service",
            "    billing-view[\"View\"]",
            "  end",
            "  core[\"Core\"]",
            // why: `features` holds `billing`, so its member `features-shell` is drawn as itself.
            "  features-shell",
            // why: a solid and a dotted edge merge into a solid one, and their labels differ.
            "  billing-service --> core",
            "  billing-view --> billing-service",
            "  billing-view -->|test| core",
            "  features-shell --> billing-view",
        ]
    );
}

#[test]
fn focus_leaves_out_edges_between_outside_ends_and_open_arrows() {
    let text = drawn(&PictureView::Focus("search".to_owned()));
    assert!(!text.contains("app"), "{text}");
    assert!(!text.contains("==>"), "{text}");
    assert!(text.contains("  search-view -->|type| core\n"), "{text}");
}

#[test]
fn focus_on_an_outer_boundary_hides_the_inside_of_the_outside() {
    let text = drawn(&PictureView::Focus("features".to_owned()));
    assert!(
        text.contains("  app[\"App\"]\n  core[\"Core\"]\n"),
        "{text}"
    );
    assert!(text.contains("  app --> features-shell\n"), "{text}");
    assert!(text.contains("  features --> core\n"), "{text}");
    assert!(text.contains("    subgraph billing"), "{text}");
}

#[test]
fn focus_merges_edges_that_reach_the_same_outside_end() {
    let edges = [
        "  billing-view -->|type| core-ui",
        "  billing-view -->|type| core-db",
    ];
    let text = picture(
        &contract(&edges),
        &PictureView::Focus("billing".to_owned()),
        "a.mmd",
    )
    .unwrap();
    assert!(text.contains("  billing-view -->|type| core\n"), "{text}");
    assert_eq!(text.matches("billing-view -->").count(), 1, "{text}");
}

#[test]
fn a_depth_of_zero_and_a_focus_that_is_no_boundary_are_errors() {
    let c = contract(&EDGES);
    assert_eq!(
        picture(&c, &PictureView::Depth(0), "a.mmd"),
        Err(PictureError::ZeroDepth)
    );
    assert_eq!(
        picture(&c, &PictureView::Focus("nowhere".to_owned()), "a.mmd"),
        Err(PictureError::UnknownBoundary("nowhere".to_owned()))
    );
    assert_eq!(
        picture(&c, &PictureView::Focus("core-ui".to_owned()), "a.mmd"),
        Err(PictureError::NotABoundary("core-ui".to_owned()))
    );
}

#[test]
fn the_order_of_declarations_does_not_change_the_picture() {
    let mut reversed: Vec<&str> = EDGES.to_vec();
    reversed.reverse();
    let (a, b) = (contract(&EDGES), contract(&reversed));
    for view in [
        PictureView::Full,
        PictureView::Depth(1),
        PictureView::Depth(2),
        PictureView::Focus("billing".to_owned()),
    ] {
        assert_eq!(
            picture(&a, &view, "a.mmd"),
            picture(&b, &view, "a.mmd"),
            "{view:?}"
        );
    }
    assert_eq!(drawn(&PictureView::Full), drawn(&PictureView::Full));
}

