#[test]
fn when_every_node_owns_a_file_the_picture_is_the_design_apart_from_the_header() {
    let every = owning(&[
        "app-main",
        "billing-controller",
        "billing-view",
        "orders-controller",
        "orders-view",
        "ui-kit",
    ]);
    for view in [
        PictureView::Full,
        PictureView::Depth(1),
        PictureView::Focus("billing".to_owned()),
    ] {
        let design = picture(&contract(), &view, false, None, "a.mmd").unwrap();
        let drawn = picture(&contract(), &view, false, Some(&every), "a.mmd").unwrap();
        assert_eq!(
            design.lines().skip(1).collect::<Vec<_>>(),
            drawn.lines().skip(1).collect::<Vec<_>>(),
            "{view:?}"
        );
        assert!(
            drawn
                .lines()
                .next()
                .unwrap()
                .contains(" --built from a.mmd;")
        );
    }
}

