const END: &str = "<!-- driftwall render end -->\n";

fn block(args: &str) -> String {
    format!("<!-- driftwall render {args} -->\n{END}")
}

#[test]
fn a_marker_takes_built_in_any_order_with_the_other_flags() {
    let owners = all_but_orders_view();
    let run = |args: &str| sync(&block(args), &contract(), Some(&owners), "a.mmd").unwrap();
    let one = run("--focus features --built --short-labels");
    let two = run("--built --short-labels --focus features");
    let three = run("--short-labels --focus features --built");
    let body = |text: &str| text.lines().skip(1).collect::<Vec<_>>().join("\n");
    assert_eq!(body(&one.text), body(&two.text));
    assert_eq!(body(&one.text), body(&three.text));
    assert!(
        one.text
            .contains("--focus features --short-labels --built from a.mmd"),
        "{}",
        one.text
    );
    assert!(one.text.contains("(no files)"), "{}", one.text);
    let alone = run("--built");
    assert!(alone.text.contains("--built from a.mmd"), "{}", alone.text);
}

#[test]
fn a_built_marker_without_ownership_is_an_error_and_other_blocks_do_not_need_it() {
    assert_eq!(
        sync(&block("--built"), &contract(), None, "a.mmd"),
        Err(PictureError::NeedsOwnership { line: 1 })
    );
    assert!(sync(&block("--depth 1"), &contract(), None, "a.mmd").is_ok());
    assert!(wants_built(&block("--depth 1 --built")));
    assert!(!wants_built(&block("--depth 1")));
    assert!(!wants_built("text mentioning --built, no marker\n"));
    for bad in ["--built --built", "--built x", "--bult"] {
        assert!(
            matches!(
                sync(&block(bad), &contract(), Some(&owning(&[])), "a.mmd"),
                Err(PictureError::BadMarker { line: 1, .. })
            ),
            "{bad}"
        );
    }
}

#[test]
fn a_built_block_goes_stale_when_ownership_changes() {
    let markdown = block("--built");
    let before = sync(
        &markdown,
        &contract(),
        Some(&all_but_orders_view()),
        "a.mmd",
    )
    .unwrap();
    assert_eq!(before.stale, [1]);
    let again = sync(
        &before.text,
        &contract(),
        Some(&all_but_orders_view()),
        "a.mmd",
    )
    .unwrap();
    assert_eq!(again.stale, Vec::<u32>::new());
    let grown = owning(&[
        "app-main",
        "billing-controller",
        "billing-view",
        "orders-controller",
        "orders-view",
        "ui-kit",
    ]);
    let after = sync(&before.text, &contract(), Some(&grown), "a.mmd").unwrap();
    assert_eq!(after.stale, [1]);
}
