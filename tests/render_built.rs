//! `driftwall render --built` through the binary: the picture of what is built, and the Markdown
//! blocks that carry the flag (see "Contract picture" in `docs/DESIGN.md`).

// why: clippy's allow-*-in-tests covers only cfg(test) code, and these helpers are not #[test] fns.
#[cfg(test)]
mod support {
    use std::fs;
    use std::path::Path;
    use std::process::{Command, Output};

    use tempfile::TempDir;

    /// Open chain `app > features > ui`, `billing` split (its view owns a file) and `orders` not
    /// split yet (its view is declared and owns nothing), and the template `view --> ui`.
    pub const CONTRACT: &str = "flowchart LR
  subgraph app[\"App\"]
    app-main
  end
  subgraph features[\"Features\"]
    subgraph billing[\"Billing: invoices\"]
      billing-controller
      billing-view[\"View\"]
    end
    subgraph orders[\"Orders\"]
      orders-controller
      orders-view
    end
  end
  subgraph ui[\"Ui\"]
    ui-kit
  end
  %% order open: app > features > ui
  %% each features: controller -->|test| view, view --> ui
  %% map app-main: src/app/
  %% map billing-*: src/features/billing/
  %% map orders-*: src/features/orders/
  %% map ui-kit: src/ui/
";

    pub fn repo(extra: &[(&str, &str)]) -> TempDir {
        let dir = TempDir::new().unwrap();
        let files = [
            ("architecture.mmd", CONTRACT),
            ("src/app/main.ts", "export const m = 1;\n"),
            ("src/ui/kit.ts", "export const k = 1;\n"),
            (
                "src/features/billing/controller.ts",
                "export const c = 1;\n",
            ),
            ("src/features/billing/view.ts", "export const v = 1;\n"),
            ("src/features/orders/controller.ts", "export const c = 1;\n"),
        ];
        for (path, body) in files.into_iter().chain(extra.iter().copied()) {
            let full = dir.path().join(path);
            fs::create_dir_all(full.parent().unwrap()).unwrap();
            fs::write(full, body).unwrap();
        }
        dir
    }

    pub fn run(root: &Path, args: &[&str]) -> Output {
        let mut command = Command::new(env!("CARGO_BIN_EXE_driftwall"));
        // why: a hook that runs the tests must not point git at the repository being committed.
        for (name, _) in std::env::vars_os() {
            if name.to_string_lossy().starts_with("GIT_") {
                command.env_remove(name);
            }
        }
        command.args(args).current_dir(root).output().unwrap()
    }

    pub fn out(output: &Output) -> String {
        String::from_utf8_lossy(&output.stdout).into_owned()
    }

    pub fn err(output: &Output) -> String {
        String::from_utf8_lossy(&output.stderr).into_owned()
    }

    pub fn read(root: &Path, path: &str) -> String {
        fs::read_to_string(root.join(path)).unwrap()
    }
}

use support::{err, out, read, repo, run};

#[test]
fn a_split_and_an_unsplit_feature_side_by_side_in_a_focus_picture() {
    let dir = repo(&[]);
    let text = out(&run(
        dir.path(),
        &["render", "--focus", "features", "--built"],
    ));
    assert_eq!(
        text,
        "%% generated by driftwall render --focus features --built from architecture.mmd; do not edit
flowchart TB
  subgraph features[\"Features\"]
    subgraph billing[\"Billing: invoices\"]
      billing-controller
      billing-view[\"View\"]
    end
    subgraph orders[\"Orders\"]
      orders-controller
      orders-view[\"orders-view (no files)\"]
    end
  end
  app[\"App\"]
  ui[\"Ui\"]
  billing-controller -->|test| billing-view
  billing-view --> ui
  orders-controller -.->|test| orders-view
  orders-view -.-> ui
  app ==>|open| features
  features ==>|open| ui
  classDef empty stroke-dasharray: 5 5
  class orders-view empty
"
    );
}

#[test]
fn without_the_flag_the_picture_is_the_contract_alone_whatever_the_code_is() {
    let built = repo(&[]);
    let bare = repo(&[]);
    std::fs::remove_dir_all(bare.path().join("src")).unwrap();
    for args in [
        &["render"][..],
        &["render", "--depth", "2"],
        &["render", "--focus", "features"],
        &["render", "--short-labels"],
    ] {
        let with_code = out(&run(built.path(), args));
        assert_eq!(with_code, out(&run(bare.path(), args)), "{args:?}");
        assert!(!with_code.contains("(no files)"), "{args:?}");
        assert!(!with_code.contains("classDef"), "{args:?}");
        assert!(!with_code.contains("--built"), "{args:?}");
    }
    // why: the design draws the template as solid for orders, which the flag then dots.
    let design = out(&run(built.path(), &["render", "--focus", "features"]));
    assert!(design.contains("  orders-view --> ui\n"), "{design}");
}

#[test]
fn the_flag_reads_the_ownership_the_way_lint_does() {
    // why: without `src`, every node is empty, and a split feature is not special.
    let dir = repo(&[]);
    std::fs::remove_dir_all(dir.path().join("src")).unwrap();
    let text = out(&run(dir.path(), &["render", "--built"]));
    assert!(
        text.contains("      billing-view[\"View (no files)\"]\n"),
        "{text}"
    );
    assert!(
        text.contains("  class app-main,billing-controller,billing-view,orders-controller,orders-view,ui-kit empty\n"),
        "{text}"
    );
    assert!(text.contains("  billing-view -.-> ui\n"), "{text}");
}

#[test]
fn depth_with_built_marks_a_box_empty_only_when_none_of_its_nodes_owns_a_file() {
    let dir = repo(&[]);
    let text = out(&run(dir.path(), &["render", "--depth", "2", "--built"]));
    assert_eq!(
        text,
        "%% generated by driftwall render --depth 2 --built from architecture.mmd; do not edit
flowchart TB
  subgraph app[\"App\"]
    app-main
  end
  subgraph features[\"Features\"]
    billing[\"Billing: invoices\"]
    orders[\"Orders\"]
  end
  subgraph ui[\"Ui\"]
    ui-kit
  end
  billing --> ui
  orders -.-> ui
  app ==>|open| features
  features ==>|open| ui
"
    );
    // why: with no file of `orders` at all the box is empty, and the merged arrow stays dotted.
    let none = repo(&[]);
    std::fs::remove_file(none.path().join("src/features/orders/controller.ts")).unwrap();
    let text = out(&run(none.path(), &["render", "--depth", "2", "--built"]));
    assert!(
        text.contains("    orders[\"Orders (no files)\"]\n"),
        "{text}"
    );
    assert!(text.ends_with("  class orders empty\n"), "{text}");
}

#[test]
fn an_open_arrow_follows_the_ownership_aware_narrowing_of_lint() {
    let dir = repo(&[("src/features/orders/view.ts", "export const v = 1;\n")]);
    let split = out(&run(
        dir.path(),
        &["render", "--focus", "features", "--built"],
    ));
    // why: both views own a file now, so the template narrows the features' access to ui for both.
    assert!(!split.contains("features ==>|open| ui"), "{split}");
    assert!(!split.contains("(no files)"), "{split}");
    assert!(!split.contains("-.->"), "{split}");
    let unsplit = out(&run(
        repo(&[]).path(),
        &["render", "--focus", "features", "--built"],
    ));
    assert!(unsplit.contains("features ==>|open| ui"), "{unsplit}");
}

const DOC: &str = "# Architecture

<!-- driftwall render --focus features --built -->
<!-- driftwall render end -->

<!-- driftwall render --built --depth 1 -->
<!-- driftwall render end -->

<!-- driftwall render --depth 1 -->
<!-- driftwall render end -->
";

#[test]
fn markers_take_built_in_any_order_and_the_block_goes_stale_when_ownership_changes() {
    let dir = repo(&[]);
    let root = dir.path();
    std::fs::write(root.join("doc.md"), DOC).unwrap();
    let update = run(root, &["render", "--update", "doc.md"]);
    assert_eq!(update.status.code(), Some(0), "{}", err(&update));
    let focus = out(&run(root, &["render", "--focus", "features", "--built"]));
    let depth = out(&run(root, &["render", "--depth", "1", "--built"]));
    let plain = out(&run(root, &["render", "--depth", "1"]));
    assert_eq!(
        read(root, "doc.md"),
        format!(
            "# Architecture

<!-- driftwall render --focus features --built -->
```mermaid
{focus}```
<!-- driftwall render end -->

<!-- driftwall render --built --depth 1 -->
```mermaid
{depth}```
<!-- driftwall render end -->

<!-- driftwall render --depth 1 -->
```mermaid
{plain}```
<!-- driftwall render end -->
"
        )
    );
    assert!(depth.starts_with("%% generated by driftwall render --depth 1 --built from"));
    let check = run(root, &["render", "--check", "doc.md"]);
    assert_eq!(check.status.code(), Some(0), "{}", err(&check));
    // why: the view of `orders` gets its first file, so the built blocks are stale and the plain one is not.
    std::fs::write(
        root.join("src/features/orders/view.ts"),
        "export const v = 1;\n",
    )
    .unwrap();
    let stale = run(root, &["render", "--check", "doc.md"]);
    assert_eq!(stale.status.code(), Some(1), "{}", err(&stale));
    let text = out(&stale);
    assert!(
        text.contains("doc.md:3: stale driftwall render block"),
        "{text}"
    );
    assert!(
        !text.contains("doc.md:9:"),
        "the plain block does not read the code: {text}"
    );
    let update = run(root, &["render", "--update", "doc.md"]);
    assert_eq!(update.status.code(), Some(0), "{}", err(&update));
    let check = run(root, &["render", "--check", "doc.md"]);
    assert_eq!(check.status.code(), Some(0), "{}", err(&check));
}

#[test]
fn a_file_with_no_built_block_is_synced_from_the_contract_alone() {
    // why: without `src` a scan would find nothing, and a plain block must not care.
    let dir = repo(&[]);
    std::fs::write(
        dir.path().join("doc.md"),
        "<!-- driftwall render --depth 1 -->\n<!-- driftwall render end -->\n",
    )
    .unwrap();
    let update = run(dir.path(), &["render", "--update", "doc.md"]);
    assert_eq!(update.status.code(), Some(0), "{}", err(&update));
    assert!(!read(dir.path(), "doc.md").contains("--built"));
}

#[test]
fn built_conflicts_with_update_and_check_and_a_bad_marker_exits_2() {
    let dir = repo(&[]);
    for args in [
        &["render", "--built", "--update", "a.md"][..],
        &["render", "--built", "--check", "a.md"],
    ] {
        let output = run(dir.path(), args);
        assert_eq!(output.status.code(), Some(2), "{args:?}");
        assert_eq!(out(&output), "", "{args:?}");
    }
    std::fs::write(
        dir.path().join("bad.md"),
        "<!-- driftwall render --built --built -->\n<!-- driftwall render end -->\n",
    )
    .unwrap();
    let bad = run(dir.path(), &["render", "--check", "bad.md"]);
    assert_eq!(bad.status.code(), Some(2));
    assert!(err(&bad).contains("line 1"), "{}", err(&bad));
}
