#[test]
fn render_takes_a_path_and_a_contract_file_and_names_it_in_the_header() {
    let dir = repo(&[("docs/design.mmd", CONTRACT)]);
    let output = run(
        std::path::Path::new("."),
        &[
            "render",
            dir.path().to_str().unwrap(),
            "--contract",
            "docs/design.mmd",
            "--depth",
            "1",
        ],
    );
    assert_eq!(output.status.code(), Some(0), "{}", err(&output));
    assert!(
        out(&output).starts_with(
            "%% generated by driftwall render --depth 1 from design.mmd; do not edit\n"
        ),
        "{}",
        out(&output)
    );
}

#[test]
fn depth_draws_boxes_and_merges_edges_by_the_merge_rules() {
    let dir = contract_only();
    let one = out(&run(dir.path(), &["render", "--depth", "1"]));
    assert_eq!(
        one,
        "%% generated by driftwall render --depth 1 from architecture.mmd; do not edit
flowchart LR
  app[\"App\"]
  features[\"Features\"]
  shared[\"Shared\"]
  app --> features
  features --> shared
  app ==>|open| features
  features ==>|open| shared
"
    );
    let two = out(&run(dir.path(), &["render", "--depth", "2"]));
    assert!(
        two.contains("  subgraph features[\"Features\"]\n    billing[\"Billing\"]\n    search[\"Search\"]\n  end\n"),
        "{two}"
    );
    // why: test + type differ so the label goes; solid beats dotted for the other pair.
    assert!(two.contains("  billing --> shared-ui\n"), "{two}");
    assert!(two.contains("  billing -.-> shared-db\n"), "{two}");
    assert!(two.contains("  search -->|type| shared-ui\n"), "{two}");
    assert!(two.contains("  app-main --> billing\n"), "{two}");
    assert!(!two.contains("billing --> billing"), "{two}");
}

