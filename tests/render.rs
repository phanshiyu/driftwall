#[test]
fn bad_arguments_exit_2() {
    let dir = contract_only();
    for args in [
        &["render", "--depth", "0"][..],
        &["render", "--depth", "x"],
        &["render", "--depth", "1", "--focus", "billing"],
        &["render", "--focus", "nowhere"],
        &["render", "--focus", "billing-view"],
        &["render", "--update", "a.md", "--depth", "1"],
        &["render", "--check", "a.md", "--focus", "billing"],
        &["render", "--update", "a.md", "--check", "a.md"],
        &["render", "--contract", "missing.mmd"],
    ] {
        let output = run(dir.path(), args);
        assert_eq!(output.status.code(), Some(2), "{args:?}: {}", err(&output));
        assert_eq!(out(&output), "", "{args:?}");
    }
}

const DOC: &str = "# Architecture

Overview:

<!-- driftwall render --depth 1 -->
stale text
<!-- driftwall render end -->

One feature:

<!-- driftwall render --focus billing -->
<!-- driftwall render end -->

Footer.
";

#[test]
fn update_then_check_then_a_contract_edit_then_update() {
    let dir = repo(&[("architecture.mmd", CONTRACT), ("doc.md", DOC)]);
    let root = dir.path();
    let before = run(root, &["render", "--check", "doc.md"]);
    assert_eq!(before.status.code(), Some(1), "{}", err(&before));
    assert!(out(&before).contains("doc.md:5: stale"), "{}", out(&before));
    assert!(
        out(&before).contains("doc.md:11: stale"),
        "{}",
        out(&before)
    );
    assert_eq!(read(root, "doc.md"), DOC, "check changes nothing");

    let update = run(root, &["render", "--update", "doc.md"]);
    assert_eq!(update.status.code(), Some(0), "{}", err(&update));
    let updated = read(root, "doc.md");
    let overview = out(&run(root, &["render", "--depth", "1"]));
    let feature = out(&run(root, &["render", "--focus", "billing"]));
    assert_eq!(
        updated,
        format!(
            "# Architecture

Overview:

<!-- driftwall render --depth 1 -->
```mermaid
{overview}```
<!-- driftwall render end -->

One feature:

<!-- driftwall render --focus billing -->
```mermaid
{feature}```
<!-- driftwall render end -->

Footer.
"
        )
    );
    let after = run(root, &["render", "--check", "doc.md"]);
    assert_eq!(after.status.code(), Some(0), "{}", err(&after));

    write(
        root,
        "architecture.mmd",
        &CONTRACT.replace("  app-main --> billing-view\n", ""),
    );
    let stale = run(root, &["render", "--check", "doc.md"]);
    assert_eq!(stale.status.code(), Some(1));
    assert!(out(&stale).contains("doc.md:5: stale"), "{}", out(&stale));
    assert!(out(&stale).contains("doc.md:21: stale"), "{}", out(&stale));
    assert_eq!(
        run(root, &["render", "--update", "doc.md"]).status.code(),
        Some(0)
    );
    let fixed = run(root, &["render", "--check", "doc.md"]);
    assert_eq!(fixed.status.code(), Some(0), "{}", out(&fixed));
}

#[test]
fn a_contract_edit_that_changes_one_block_names_only_that_block() {
    let dir = repo(&[("architecture.mmd", CONTRACT), ("doc.md", DOC)]);
    let root = dir.path();
    assert_eq!(
        run(root, &["render", "--update", "doc.md"]).status.code(),
        Some(0)
    );
    write(
        root,
        "architecture.mmd",
        &CONTRACT.replace("  billing-view --> billing-service\n", ""),
    );
    let stale = run(root, &["render", "--check", "doc.md"]);
    assert_eq!(stale.status.code(), Some(1));
    let text = out(&stale);
    assert!(text.contains("doc.md:21: stale"), "{text}");
    assert!(!text.contains("doc.md:5:"), "{text}");
    let fixed = run(root, &["render", "--update", "doc.md"]);
    assert_eq!(fixed.status.code(), Some(0), "{}", err(&fixed));
    assert_eq!(
        run(root, &["render", "--check", "doc.md"]).status.code(),
        Some(0)
    );
}

#[test]
fn malformed_markdown_exits_2_naming_the_line() {
    let dir = contract_only();
    let root = dir.path();
    let start = "<!-- driftwall render -->";
    let end = "<!-- driftwall render end -->";
    for (name, body, expect) in [
        ("a.md", format!("x\n{start}\ny\n"), "line 2"),
        ("b.md", format!("x\ny\n{end}\n"), "line 3"),
        ("c.md", format!("{start}\n{start}\n{end}\n"), "line 2"),
        (
            "d.md",
            format!("x\n<!-- driftwall render --bogus -->\n{end}\n"),
            "line 2",
        ),
        (
            "e.md",
            "no blocks\n".to_owned(),
            "no `<!-- driftwall render",
        ),
        (
            "f.md",
            format!("<!-- driftwall render --depth 0 -->\n{end}\n"),
            "depth must be at least 1",
        ),
        (
            "g.md",
            format!("<!-- driftwall render --focus nowhere -->\n{end}\n"),
            "unknown boundary `nowhere`",
        ),
    ] {
        write(root, name, &body);
        for mode in ["--check", "--update"] {
            let output = run(root, &["render", mode, name]);
            assert_eq!(output.status.code(), Some(2), "{name} {mode}");
            let message = err(&output);
            assert!(message.contains(expect), "{name} {mode}: {message}");
            assert!(message.contains(name), "{name} {mode}: {message}");
        }
        assert_eq!(read(root, name), body, "{name} stays as it was");
    }
    let missing = run(root, &["render", "--check", "missing.md"]);
    assert_eq!(missing.status.code(), Some(2));
}
