//! `driftwall render` through the binary: the picture, its flags and the Markdown blocks (see
//! "Contract picture" in `docs/DESIGN.md`).

// why: clippy's allow-*-in-tests covers only cfg(test) code, and these helpers are not #[test] fns.
#[cfg(test)]
mod support {
    use std::fs;
    use std::path::Path;
    use std::process::{Command, Output};

    use tempfile::TempDir;

    /// Two features of two parts, a shared boundary and an open chain. No source code: `render`
    /// needs the contract only.
    pub const CONTRACT: &str = "flowchart LR
  subgraph app[\"App\"]
    app-main
  end
  subgraph features[\"Features\"]
    subgraph billing[\"Billing\"]
      billing-view[\"View\"]
      billing-service
    end
    subgraph search[\"Search\"]
      search-view
    end
  end
  subgraph shared[\"Shared\"]
    shared-ui
    shared-db
  end
  billing-view --> billing-service
  billing-view -->|test| shared-ui
  billing-service -->|type| shared-ui
  billing-service -.-> shared-db
  search-view -->|type| shared-ui
  app-main --> billing-view
  %% order open: app > features > shared
";

    pub fn repo(files: &[(&str, &str)]) -> TempDir {
        let dir = TempDir::new().unwrap();
        for (path, body) in files {
            let full = dir.path().join(path);
            fs::create_dir_all(full.parent().unwrap()).unwrap();
            fs::write(full, body).unwrap();
        }
        dir
    }

    pub fn run(root: &Path, args: &[&str]) -> Output {
        let mut command = Command::new(env!("CARGO_BIN_EXE_driftwall"));
        // why: a hook that runs the tests must not point git at the repository being committed.
        for (name, _) in std::env::vars_os() {
            if name.to_string_lossy().starts_with("GIT_") {
                command.env_remove(name);
            }
        }
        command.args(args).current_dir(root).output().unwrap()
    }

    pub fn out(output: &Output) -> String {
        String::from_utf8_lossy(&output.stdout).into_owned()
    }

    pub fn err(output: &Output) -> String {
        String::from_utf8_lossy(&output.stderr).into_owned()
    }

    pub fn read(root: &Path, path: &str) -> String {
        fs::read_to_string(root.join(path)).unwrap()
    }

    pub fn write(root: &Path, path: &str, body: &str) {
        fs::write(root.join(path), body).unwrap();
    }
}

use support::{CONTRACT, err, out, read, repo, run, write};

fn contract_only() -> tempfile::TempDir {
    repo(&[("architecture.mmd", CONTRACT)])
}

